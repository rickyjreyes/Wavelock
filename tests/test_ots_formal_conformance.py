class SimulatedCrash(BaseException):
    """Process death at a modelled point. Not an ``Exception``: no handler may absorb it."""


def _legacy_index_signature(self, signature):
    """``PersistentOTSReplayLedger.index_signature`` at ``b310ea5``."""
    if not isinstance(signature, dict):
        return
    kid, leaf = ots_ledger._ids_for(signature)
    with self._lock:
        if kid != "None":
            self._key_ids.add(kid)
        if leaf != "None":
            self._leaf_ids.add(leaf)


def _kid_value(spec):
    if "str" in spec:
        return spec["str"]
    if "null" in spec:
        return None
    if "num" in spec:
        return spec["num"]
    return list(spec["arr"])


def _relabel(keypair, kid):
    pk, sk = copy.deepcopy(keypair["public_key"]), copy.deepcopy(keypair["secret_key"])
    pk["one_time_key_id"] = sk["one_time_key_id"] = kid
    pk["public_key_fingerprint"] = sk["public_key_fingerprint"] = ots.public_key_fingerprint(pk)
    return pk, sk


def _manual_block(index, prev, messages, meta, timestamp):
    return Block(index=index, messages=messages, previous_hash=prev, difficulty=0,
                 block_type="OTS", meta=meta, timestamp=timestamp, header_version=2)


def _build_block(spec, pk, sk, label):
    index, prev = spec["index"], spec["prev_hash"]
    body = [spec.get("body", f"ots: {label}")]
    tamper = spec.get("tamper")
    if tamper in (None, "body", "slice", "legacy"):
        block = build_signed_ots_block(sk, pk, body, index=index, previous_hash=prev,
                                       difficulty=0, allow_reuse=True)
        if tamper is None:
            return block
        meta = copy.deepcopy(block.meta)
        if tamper == "body":
            return _manual_block(index, prev, ["pay attacker 5000000"], meta, block.timestamp)
        if tamper == "slice":
            meta["ots_auth"]["signature"]["revealed_slices"][0] = "00" * 32
        else:
            meta["ots_auth"]["signature"] = {"scheme": "WLv2", "signature": "deadbeef" * 8}
        return _manual_block(index, prev, body, meta, block.timestamp)
    timestamp = str(time.time())
    header = {"version": 2, "index": index, "timestamp": timestamp, "difficulty": 0}
    if tamper == "unbound":
        signature = ots.sign_ots(sk, "hello world", allow_reuse=True)
        meta = build_ots_block_meta(pk, "hello world", signature)
        meta["block_header"] = header
        return _manual_block(index, prev, body, meta, timestamp)
    assert tamper == "fingerprint"
    pk, sk = copy.deepcopy(pk), copy.deepcopy(sk)
    pk["public_key_fingerprint"] = sk["public_key_fingerprint"] = "0" * 64
    draft = _manual_block(index, prev, body,
                          {"block_header": header, "auth_scheme": ots.SCHEME,
                           "ots_auth": {"public_key": pk}}, timestamp)
    digest = canonical_ots_block_digest(draft)
    meta = build_ots_block_meta(pk, digest, ots.sign_ots(sk, digest, allow_reuse=True))
    meta["block_header"] = header
    return _manual_block(index, prev, body, meta, timestamp)


def build_blocks(trace):
    keys, built = {}, {}
    for label, spec in trace["blocks"].items():  # parents precede children
        keypair = keys.setdefault(spec["key"], ots.generate_ots_keypair())
        pk, sk = _relabel(keypair, _kid_value(spec["kid"]))
        prev = "0" * 64 if spec["parent"] is None else built[spec["parent"]].hash
        built[label] = _build_block({**spec, "prev_hash": prev}, pk, sk, label)
    return built


def _logical_records(path):
    """Complete JSON objects of a JSONL file, including merged or unterminated lines."""
    if not os.path.exists(path):
        return []
    decoder, out = json.JSONDecoder(), []
    with open(path, encoding="utf-8") as fh:
        for line in fh.read().split("\n"):
            i = 0
            while i < len(line):
                try:
                    obj, i = decoder.raw_decode(line, i)
                except json.JSONDecodeError:
                    break  # torn fragment: not part of the logical content
                out.append(obj)
    return out


class _Discard:
    def index_signature(self, signature):
        pass


class Host:
    """One host: shared replay/chain files and several processes (ledger + chain objects)."""

    def __init__(self, tmp_path, monkeypatch, legacy):
        self.dir = tmp_path / "ledger"
        self.dir.mkdir()
        self.replay_path = str(self.dir / "ots_replay.jsonl")
        self.chain_file = self.dir / "blk00000.jsonl"
        self.mp = monkeypatch
        monkeypatch.setattr(chain_utils, "LEDGER_DIR", self.dir)
        monkeypatch.setattr(chain_utils, "LEDGER_FILE", self.chain_file)
        monkeypatch.setattr(server, "broadcast_inv", lambda h: None)
        if legacy:
            monkeypatch.setattr(PersistentOTSReplayLedger, "index_signature", _legacy_index_signature)
            monkeypatch.setattr(ots_ledger, "_identity_types_ok", lambda signature: True)
        self.cfg = Config()
        self.cfg.require_ots = True
        self.cfg.pow_target = "f" * 64
        self.procs = {}

    def _start(self):
        try:
            return PersistentOTSReplayLedger(path=self.replay_path), server.ChainState(persistent=True)
        except OTSLedgerError:
            return None

    def _proc(self, pid):
        if pid not in self.procs:
            self.procs[pid] = self._start()
        proc = self.procs[pid]
        if proc is not None:
            self.mp.setattr(server, "CONSENSUS_OTS_LEDGER", proc[0])
            self.mp.setattr(server, "CHAIN", proc[1])
        return proc

    @contextlib.contextmanager
    def _faults(self, ledger, record, block):
        inner = pytest.MonkeyPatch()
        try:
            if record != "ok":
                inner.setattr(ledger, "_append", self._record_fault(ledger, record))
            if block != "ok":
                inner.setattr(server, "save_block_to_disk", self._block_fault(block))
            yield
        finally:
            inner.undo()

    def _record_fault(self, ledger, kind):
        real = ledger._append

        def append(kid, leaf, transcript):
            line = json.dumps({"v": ots_ledger.LEDGER_VERSION, "one_time_key_id": kid,
                               "leaf_id": leaf, "transcript": transcript},
                              separators=(",", ":"), sort_keys=True)
            if kind == "fail_before_write":
                raise OSError("injected: nothing written")
            if kind == "fail_after_write":
                with pytest.MonkeyPatch.context() as m:
                    m.setattr(ots_ledger, "fsync_directory", _raise_os_error)
                    real(kid, leaf, transcript)
            with open(self.replay_path, "a", encoding="utf-8") as fh:
                fh.write(line[: len(line) // 2] if kind == "crash_torn" else line)
            raise SimulatedCrash(kind)
        return append

    def _block_fault(self, kind):
        def save(block):
            line = json.dumps(block.to_dict())
            if kind == "fail_before_write":
                raise OSError("injected: nothing written")
            if kind == "fail_after_write":
                chain_utils.save_block_to_disk(block)
                raise OSError("injected after the line was written")
            if kind != "crash_before_write":
                with open(self.chain_file, "a", encoding="utf-8") as fh:
                    fh.write(line[: len(line) // 2] if kind == "crash_torn" else line)
            raise SimulatedCrash(kind)
        return save

    def accept(self, pid, block, record="ok", block_outcome="ok"):
        proc = self._proc(pid)
        if proc is None:
            return False
        with self._faults(proc[0], record, block_outcome):
            try:
                return bool(server.try_accept_block_dict(block.to_dict(), self.cfg))
            except SimulatedCrash:
                self.procs[pid] = None
                return False
            except Exception:  # anything escaping acceptance is a rejection
                return False

    def pay(self, pid, block):
        proc = self._proc(pid)
        if proc is None:
            return False
        auth = block.meta["ots_auth"]
        return server.verify_ots_payload(auth["public_key"], auth["message"], auth["signature"],
                                         ledger=proc[0])

    def crash(self, pid):
        self.procs[pid] = None

    def restart(self, pid):
        if self.procs.get(pid, "never started") is not None:
            return
        proc = self._start()
        if proc is not None:
            self.mp.setattr(server, "CONSENSUS_OTS_LEDGER", proc[0])
            self.mp.setattr(server, "CHAIN", proc[1])
            try:
                proc[1].load_from_disk(require_ots=True)
            except Exception:
                proc = None
        self.procs[pid] = proc

    def delete_replay(self):
        if os.path.exists(self.replay_path):
            os.remove(self.replay_path)

    def chain_loads(self):
        try:
            blocks = chain_utils.load_all_blocks()
            if not verify_ots_chain(blocks):
                return False
            server._reconstruct_consumed_ots(blocks, _Discard())
            return True
        except Exception:
            return False

    def replay_loads(self):
        try:
            PersistentOTSReplayLedger(path=self.replay_path)
            return True
        except OTSLedgerError:
            return False


def _identity(block):
    signature = block.meta["ots_auth"]["signature"]
    return str(signature["one_time_key_id"]), str(signature["public_key_fingerprint"])


