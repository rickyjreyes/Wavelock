#!/usr/bin/env python3
"""Generate lean/WaveLockProofs/OTSSignerConformance.lean from lean/ots_signer_traces.json.

The traces exercise the preexisting WaveLock-OTS signing guard (``wavelock_ots.sign_ots`` and its
host-local key-state registry) and are evaluated against ``lean/WaveLockProofs/OTSSignerGuard.lean``.
Each trace becomes one Lean theorem checked by ``decide``.  ``tests/test_ots_signer_conformance.py``
replays the same traces against the Python code, checks the same expected outcome, and checks that
the committed Lean file is this script's output.

    python scripts/gen_ots_signer_conformance.py --write
"""
from __future__ import annotations

import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
TRACES = ROOT / "lean" / "ots_signer_traces.json"
OUT = ROOT / "lean" / "WaveLockProofs" / "OTSSignerConformance.lean"

SIGNER_REVS = {"flag_only": ".flagOnly", "c3cb0d1": ".c3cb0d1", "current": ".current"}
CLAIM_OUTCOMES = {"ok": ".ok", "fail_before": ".failBefore", "fail_after": ".failAfter"}


def load_traces() -> dict:
    return json.loads(TRACES.read_text(encoding="utf-8"))


def lean_ident(name: str) -> str:
    return "".join(c if c.isalnum() else "_" for c in name)


def num(label: str) -> int:
    """Trailing number of a label such as ``p0``, ``f1``, ``d0`` or ``c2``."""
    digits = "".join(c for c in label if c.isdigit())
    return int(digits)


def lean_bool(b: bool) -> str:
    return "true" if b else "false"


def lean_list(items) -> str:
    return "[" + ", ".join(items) + "]"


def signer_markers(rev: str, kid: int, mat: int, allow: bool) -> int:
    if allow or rev == "flag_only":
        return 0
    return 1 if rev == "c3cb0d1" else 2


def signer_events(trace: dict) -> list:
    rev = trace["rev"]
    files: dict = {}
    out = []
    for ev in trace["events"]:
        kind = ev[0]
        if kind == "key":
            _, f, kid, mat = ev
            files[f] = (kid, mat)
            out.append(f".mkFile {num(f)} {kid} {mat}")
        elif kind in ("sign", "sign_allow_reuse", "sign_claim_fail", "sign_crash_after_claims"):
            p, f, d, msg = ev[1], ev[2], ev[3], ev[4]
            allow = kind == "sign_allow_reuse"
            ev_rev = ev[5] if kind == "sign" and len(ev) > 5 else rev
            kid, mat = files[f]
            n = signer_markers(ev_rev, kid, mat, allow)
            outcomes = ["ok"] * n
            if kind == "sign_claim_fail":
                index, outcome = ev[5], ev[6]
                outcomes = outcomes[:index] + [outcome]
            out.append(f".start {num(p)} {num(f)} {num(d)} {msg} {SIGNER_REVS[ev_rev]} "
                       f"{lean_bool(allow)}")
            out += [f".claim {num(p)} {CLAIM_OUTCOMES[o]}" for o in outcomes]
            if kind == "sign_crash_after_claims":
                out += [f".crash {num(p)}", f".restart {num(p)}"]
            else:
                out += [f".reveal {num(p)}", f".persist {num(p)}"]
        elif kind == "wipe":
            out.append(f".wipe {num(ev[1])}")
        elif kind == "power_loss":
            out.append(".powerLoss")
        else:
            raise ValueError(ev)
    return out


def marker_term(m) -> str:
    return f".{m[0]} {m[1]}"


def signer_section(trace: dict) -> str:
    name = lean_ident(trace["name"])
    exp = trace["expected"]
    dirs = sorted(exp["markers"])
    lines = [f"namespace {name}", "", "def trace : List OTSSigner.Event :=",
             "  " + lean_list(signer_events(trace)), "",
             f"/-- `{trace['name']}` (signer guard revision {trace['rev']}). -/",
             "theorem conformance :",
             f"    let S := OTSSigner.run {lean_bool(trace.get('dir_sync', True))} trace",
             f"    S.sigs.map (fun s => (s.kid, s.mat, s.msg)) = "
             f"{lean_list(f'({k}, {m}, {msg})' for k, m, msg in exp['sigs'])}"]
    for d in dirs:
        markers = lean_list(f"OTSSigner.Marker{marker_term(m)}" for m in exp["markers"][d])
        lines[-1] += " ∧"
        lines.append(f"      (S.reg {num(d)}).map Prod.fst = {markers}")
    lines[-1] += " := by"
    lines += ["  decide", "", f"end {name}", ""]
    return "\n".join(lines)


def render() -> str:
    traces = load_traces()["traces"]
    header = f"""import WaveLockProofs.OTSSignerGuard

/-!
# Lean/Python conformance traces for the WaveLock-OTS signing guard (generated)

GENERATED by `scripts/gen_ots_signer_conformance.py` from `lean/ots_signer_traces.json`.
Do not edit by hand; `tests/test_ots_signer_conformance.py` fails if this file drifts.

Each of the {len(traces)} theorems evaluates `OTSSignerGuard.run` on one trace and checks, with
`decide`, the signatures that leave `sign_ots` and the markers of each registry directory.  The same
traces are replayed against the real Python code: real key files and registries, claim failures
and a crash injected at the modelled points, and the `c3cb0d1` guard (key-id claim only) and the
pre-registry guard emulated by disabling the corresponding claims.  Agreement on finite traces is
evidence that the model describes the code; it is not a refinement proof.
-/

namespace WaveLockProofs
namespace OTSSignerConformance

"""
    body = "\n".join(signer_section(t) for t in traces)
    return header + body + "end OTSSignerConformance\nend WaveLockProofs\n"


if __name__ == "__main__":
    text = render()
    if "--write" in sys.argv:
        OUT.write_text(text, encoding="utf-8")
        print(f"wrote {OUT.relative_to(ROOT)}")
    else:
        sys.stdout.write(text)
